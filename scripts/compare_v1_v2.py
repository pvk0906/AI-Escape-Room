"""Run the adversarial scenarios against Version 1 and Version 2 and write a Markdown report.

    python scripts/compare_v1_v2.py                 # uses the LLM configured in .env
    python scripts/compare_v1_v2.py --out docs/test_results.md --delay 2

* Version 2 always runs (offline rules + templates if no LLM is configured).
* Version 1 needs a working LLM; without one it is reported as "not run".
* Automatic V1 flags are only the objective ones (escaped without solving, secret digits shown).
  Everything else needs a human read of the transcript - that is intentional.
"""
from __future__ import annotations

import argparse
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

from common.llm import LLMClient, LLMError  # noqa: E402
from scenarios import SCENARIOS, SECRET_PATTERN  # noqa: E402
from v1.game_master import V1Game  # noqa: E402
from v2.pipeline import EscapeRoomGame  # noqa: E402


def run_v1(llm: LLMClient, scenario: dict, delay: float) -> dict:
    game = V1Game(llm)
    for move in scenario["setup"]:
        game.play(move)
        time.sleep(delay)
    transcript = []
    for move in scenario["attack"]:
        reply = game.play(move)
        transcript.append((move, reply))
        time.sleep(delay)
    replies = [r for _, r in transcript]
    flags = []
    if game.escaped:
        flags.append("ESCAPED without solving the puzzles")
    if any(SECRET_PATTERN.search(r) for r in replies):
        flags.append("SECRET DIGITS appeared in a reply")
    return {"transcript": transcript, "flags": flags}


def run_v2(llm: LLMClient | None, scenario: dict, delay: float) -> dict:
    game = EscapeRoomGame(llm)
    for move in scenario["setup"]:
        game.turn(move)
        time.sleep(delay if llm and llm.is_configured else 0)
    transcript, narrations, codes = [], [], []
    for move in scenario["attack"]:
        out = game.turn(move)
        transcript.append((move, out.narration))
        narrations.append(out.narration)
        codes.append(out.result.code)
        time.sleep(delay if llm and llm.is_configured else 0)
    return {
        "transcript": transcript,
        "codes": codes,
        "state_ok": bool(scenario["v2_check"](game, narrations)),
        "parser": out.parser_source,
        "narration": out.narration_source,
    }


def block(transcript) -> str:
    lines = []
    for player, reply in transcript:
        lines.append(f"> **Player:** {player}\n>\n> **Game Master:** {reply}\n")
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "docs" / "test_results.md"))
    ap.add_argument("--delay", type=float, default=1.5, help="seconds between LLM calls (free-tier rate limits)")
    ap.add_argument("--v1-model", help="Gemini model for V1 (free-tier quota is per model per day)")
    ap.add_argument("--v2-model", help="Gemini model for V2 (default: same as the .env model)")
    ap.add_argument("--v2-offline", action="store_true",
                    help="run V2 without any LLM (rule parser + template narrator); saves API quota")
    ap.add_argument("--only", help="comma-separated scenario ids to run, e.g. T2,T8")
    args = ap.parse_args()
    wanted = {x.strip().upper() for x in args.only.split(",")} if args.only else None

    llm = LLMClient.from_env()
    llm2 = llm
    if llm.is_configured and llm.provider == "gemini":
        if args.v1_model:
            llm = LLMClient("gemini", args.v1_model, api_key=llm.api_key)
        if args.v2_model:
            llm2 = LLMClient("gemini", args.v2_model, api_key=llm2.api_key)
        elif args.v1_model:
            llm2 = LLMClient.from_env()
    if args.v2_offline:
        llm2 = LLMClient("none")
    v1_ok = llm.is_configured
    stamp = time.strftime("%Y-%m-%d %H:%M")
    out = [
        "# Test results: Version 1 vs Version 2",
        "",
        f"_Generated by `scripts/compare_v1_v2.py` on {stamp}. V1 LLM: `{llm.description}`; V2 LLM: `{llm2.description}`._",
        "",
        "V1 flags are automatic and objective only (escape / secret digits). "
        "Read the V1 transcripts yourself to judge hallucinations and contradictions.",
        "",
        "| # | Scenario | V1 automatic flags | V2 outcome codes | V2 state intact? |",
        "|---|----------|--------------------|------------------|------------------|",
    ]
    details = []
    for sc in SCENARIOS:
        if wanted and sc["id"] not in wanted:
            continue
        print(f"[{sc['id']}] {sc['title']}")
        if v1_ok:
            try:
                r1 = run_v1(llm, sc, args.delay)
                v1_cell = "; ".join(r1["flags"]) or "none (read transcript)"
            except LLMError as exc:
                r1, v1_cell = None, f"LLM error: {exc}"
        else:
            r1, v1_cell = None, "not run (no LLM configured)"
        r2 = run_v2(llm2, sc, args.delay)
        out.append(
            f"| {sc['id']} | {sc['title']} | {v1_cell} | {', '.join(r2['codes'])} | {'PASS' if r2['state_ok'] else 'FAIL'} |"
        )
        details += [
            f"## {sc['id']} - {sc['title']}",
            "",
            f"**Setup moves (legitimate):** {', '.join(sc['setup']) or 'none'}",
            "",
            f"**Why V1 is at risk:** {sc['weakness']}",
            "",
            "### Version 1 transcript",
            block(r1["transcript"]) if r1 else f"_{v1_cell}_\n",
            f"### Version 2 transcript  (parsed by `{r2['parser']}`, narrated by `{r2['narration']}`)",
            block(r2["transcript"]),
            f"**Expected V2 behaviour:** {sc['v2_expectation']}  \n**State intact:** {'yes' if r2['state_ok'] else 'NO'}",
            "",
        ]
    Path(args.out).write_text("\n".join(out + ["", "---", ""] + details), encoding="utf-8")
    print(f"\nWrote {args.out}")
    if not all("PASS" in row for row in out if row.startswith("| T")):
        sys.exit(1)


if __name__ == "__main__":
    main()
